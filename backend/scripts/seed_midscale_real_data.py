def ensure_learning(db, M, courses, plans, target=2500):
    LearningRecord, LearningStatus = M["LearningRecord"], M["LearningStatus"]
    Talent, TalentStatus = M["Talent"], M["TalentStatus"]
    if db.query(LearningRecord).count() >= target:
        logger.info("[learning_records] 已有 %d 条，跳过", db.query(LearningRecord).count())
        return
    talents = db.query(Talent).filter(Talent.status.in_([TalentStatus.ACTIVE, TalentStatus.RESERVE])).all()
    base = _next_seq(db, LearningRecord, LearningRecord.record_code, "LR2026") - 1
    seen = {(t, c) for t, c in db.query(LearningRecord.talent_id, LearningRecord.course_id).all()}
    batch, created = [], base
    not_started = 0
    statuses = [LearningStatus.IN_PROGRESS, LearningStatus.COMPLETED,
                LearningStatus.FAILED, LearningStatus.NOT_STARTED]

    while created < target:
        t = random.choice(talents)
        c = random.choice(courses)
        p = random.choice(plans)
        key = (t.id, c.id)
        if key in seen:
            continue
        seen.add(key)
        if not_started < 40:
            st = LearningStatus.NOT_STARTED
        else:
            st = random.choices(statuses, weights=[35, 45, 10, 10], k=1)[0]
        dur_course = c.duration_minutes or 120
        if st == LearningStatus.NOT_STARTED:
            progress, duration, last, done = 0.0, 0, None, None
            not_started += 1
        elif st == LearningStatus.IN_PROGRESS:
            progress = round(random.uniform(10, 90), 2)
            duration = random.randint(20, dur_course)
            last, done = rand_dt(days_back=20), None
        elif st == LearningStatus.COMPLETED:
            progress = 100.0
            duration = random.randint(dur_course, int(dur_course * 1.8))
            last = rand_dt(days_back=60); done = last
        else:
            progress = round(random.uniform(30, 80), 2)
            duration = random.randint(30, dur_course)
            last, done = rand_dt(days_back=60), None
        batch.append(LearningRecord(
            record_code=f"LR2026{created + 1:06d}", talent_id=t.id, course_id=c.id, plan_id=p.id,
            progress=progress, duration_minutes=duration, status=st,
            last_learning_time=last, completed_time=done, created_at=rand_dt(days_back=120),
        ))
        created += 1
        if len(batch) >= 500:
            db.add_all(batch)
            db.commit()
            batch.clear()
    if batch:
        db.add_all(batch)
        db.commit()
    logger.info("[learning_records] 新增 %d 条（其中未开始 %d 条）", created - base, not_started)


