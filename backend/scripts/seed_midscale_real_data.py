def weighted_name() -> tuple:
    """按真实姓氏频次 + 性别对应取名用字生成姓名，返回 (中文名, 拼音, 性别)"""
    surname = random.choices(SURNAMES, weights=[s[2] for s in SURNAMES], k=1)[0]
    if random.random() < 0.56:
        given = random.choice(MALE_NAMES)
        gender = "male"
    else:
        given = random.choice(FEMALE_NAMES)
        gender = "female"
    return surname[0] + given[0], surname[1] + given[1], gender


def rand_dt(days_back: int = 365, days_fwd: int = 0) -> datetime:
    """在过去 days_back 天到未来 days_fwd 天之间取一个随机时刻"""
    span = days_back + max(days_fwd, 0)
    d = random.randint(-days_fwd, days_back)
    return datetime.now() - timedelta(days=d, seconds=random.randint(0, 86399), microseconds=0)


def edu_for(level_hint: str, edu_req: str) -> str:
    """按岗位学历要求生成学历，主力集中在校验通过的最低档及以上"""
    order = ["高中", "大专", "本科", "硕士", "博士"]
    idx = order.index(edu_req) if edu_req in order else 2
    # 90% 达标（含高一档），10% 略低（用于制造不匹配样本，匹配时会被过滤）
    if random.random() < 0.10 and idx > 0:
        return order[idx - 1]
    if idx >= 3:
        return edu_req if random.random() < 0.7 else order[min(idx + 1, 4)]
    return random.choices(order[idx:min(idx + 2, 5)], weights=[80, 20], k=1)[0]


