def main() -> None:
    ap = argparse.ArgumentParser(description="中型规模真实业务数据导入（幂等）")
    ap.add_argument("--talents", type=int, default=1200)
    ap.add_argument("--positions", type=int, default=120)
    ap.add_argument("--matches", type=int, default=3000)
    ap.add_argument("--results", type=int, default=1500)
    ap.add_argument("--learning", type=int, default=2500)
    ap.add_argument("--examinations", type=int, default=1200)
    ap.add_argument("--audit", type=int, default=800)
    ap.add_argument("--reset-seeded", action="store_true",
                    help="先删除本脚本以 2026 批次前缀创建的数据再重建（不动原始数据）")
    ap.add_argument("--seed", type=int, default=20261015)
    args = ap.parse_args()

    random.seed(args.seed)
    M = _import_models()

    factory = M["get_mysql_session_factory"]()
    if factory is None:
        logger.error("MySQL 未初始化，请确认 .env 与数据库连接")
        sys.exit(1)

    db = factory()
    try:
        db.execute(text("SET NAMES utf8mb4"))
        logger.info("开始导入中型规模业务数据（真实参照维度）...")

        if args.reset_seeded:
            reset_seeded_data(db)

        code_to_id = ensure_organizations(db, M)
        users = ensure_users(db, M, code_to_id)
        ensure_talents(db, M, code_to_id, users["emp"], target=args.talents)
        ensure_positions(db, M, code_to_id, target=args.positions)
        ensure_match_records(db, M, target=args.matches)
        questions = ensure_questions(db, M)
        papers = ensure_papers(db, M, questions)
        tasks = ensure_tasks(db, M, papers)
        ensure_results(db, M, tasks, papers, target=args.results)
        courses = ensure_courses(db, M)
        plans = ensure_plans(db, M, courses)
        ensure_learning(db, M, courses, plans, target=args.learning)
        ensure_examinations(db, M, courses, plans, target=args.examinations)
        ensure_audit_logs(db, M, target=args.audit)

        _summary(db, M)
        logger.info("导入完成。")
    except Exception as e:  # noqa: BLE001
        db.rollback()
        logger.error("导入失败：%s", e, exc_info=True)
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
