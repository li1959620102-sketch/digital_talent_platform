def ensure_match_records(db, M, target=3000):
    Talent, JobPosition, MatchRecord = M["Talent"], M["JobPosition"], M["MatchRecord"]
    PositionStatus, TalentStatus = M["PositionStatus"], M["TalentStatus"]
    if db.query(MatchRecord).count() >= target:
        logger.info("[match_records] 已有 %d 条，跳过", db.query(MatchRecord).count())
        return

    positions = db.query(JobPosition).filter(JobPosition.status == PositionStatus.OPEN).all()
    if not positions:
        logger.warning("[match_records] 无在招岗位，跳过")
        return
    talents = db.query(Talent).filter(
        Talent.status.in_([TalentStatus.ACTIVE, TalentStatus.RESERVE])).all()
    if not talents:
        logger.warning("[match_records] 无可用人才，跳过")
        return

    seen = {(t, p) for t, p in db.query(MatchRecord.talent_id, MatchRecord.position_id).all()}
    batch, created = [], 0
    random.shuffle(positions)
    for pos in positions:
        if created >= target:
            break
        # 优先匹配同部门/相同学历层次的人才，使结果更真实
        pool = talents if random.random() < 0.5 else random.sample(talents, min(400, len(talents)))
        for t in pool:
            if created >= target:
                break
            key = (t.id, pos.id)
            if key in seen:
                continue
            m = compute_match_score(t, pos)
            if m["score"] <= 0:
                continue
            seen.add(key)
            batch.append(MatchRecord(
                talent_id=t.id, position_id=pos.id,
                match_score=m["score"], match_dimensions={"hard": m["score"]},
                match_basis="; ".join(m["reasons"]),
                strengths="; ".join(m["strengths"]),
                weaknesses="; ".join(m["weaknesses"]),
                suggestions=f"建议重点考察候选人在{pos.position_name}方向的实践深度。",
                status=random.choices(
                    ["pending", "shortlisted", "interviewed", "hired", "rejected"],
                    weights=[45, 25, 15, 8, 7], k=1)[0],
            ))
            created += 1
            if len(batch) >= 500:
                db.add_all(batch)
                db.commit()
                batch.clear()
    if batch:
        db.add_all(batch)
        db.commit()
    logger.info("[match_records] 新增 %d 条（来自 %d 个在招岗位）", created, len(positions))


