def _codes(db, model, column, prefix):
    return {c for (c,) in db.query(column).filter(column.like(f"{prefix}%")).all()}


def _next_seq(db, model, column, prefix):
    """返回下一个可用序号（编码为 PREFIX + 零填充数字，字典序等价于数值序）"""
    row = db.query(column).filter(column.like(f"{prefix}%")).order_by(column.desc()).first()
    if not row or not row[0]:
        return 1
    try:
        return int(row[0][len(prefix):]) + 1
    except ValueError:
        return 1


