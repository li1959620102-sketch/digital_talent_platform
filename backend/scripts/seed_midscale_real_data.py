def build_education_records(education: str, major: str, birth_year: int, city: str) -> list:
    """按学历层次生成完整的、时间连续的求学经历"""
    recs = []
    y = birth_year + 18
    if education == "高中":
        recs.append({"school": f"{city}第一中学", "major": "理科", "degree": "高中",
                     "start": f"{birth_year + 15}-09", "end": f"{y}-06"})
        return recs
    if education == "大专":
        recs.append({"school": pick_school("大专"), "major": major, "degree": "大专",
                     "start": f"{y}-09", "end": f"{y + 3}-06"})
        return recs
    recs.append({"school": pick_school("本科"), "major": major, "degree": "本科",
                 "start": f"{y}-09", "end": f"{y + 4}-06"})
    y += 4
    if education in ("硕士", "博士"):
        recs.append({"school": pick_school("硕士"), "major": major, "degree": "硕士",
                     "start": f"{y}-09", "end": f"{y + 3}-06"})
        y += 3
    if education == "博士":
        recs.append({"school": pick_school("博士"), "major": major, "degree": "博士",
                     "start": f"{y}-09", "end": f"{y + 4}-06"})
    return recs


def compute_match_score(talent, position) -> dict:
    """严格复用 app/api/v1/matching.py::compute_match_score 的算法"""
    reasons, strengths, weaknesses = [], [], []
    score = 0.0
    req_edu = position.education_requirement
    if req_edu:
        if edu_index(talent.education) >= edu_index(req_edu):
            score += 30
            reasons.append("学历满足要求")
            strengths.append(f"学历匹配（{talent.education.value if talent.education else '未知'}）")
        else:
            reasons.append("学历不满足要求")
            weaknesses.append(f"学历不足（要求{req_edu}）")
            return {"score": 0.0, "reasons": reasons, "strengths": [], "weaknesses": weaknesses}

    req_exp = position.experience_requirement or 0
    t_exp = talent.experience_years or 0
    if req_exp > 0:
        if t_exp >= req_exp:
            score += 25
            strengths.append(f"经验充足（{t_exp}年/要求{req_exp}年）")
            reasons.append(f"工作经验满足要求（{t_exp}年）")
        elif t_exp > 0:
            score += round(25 * (t_exp / req_exp), 1)
            weaknesses.append(f"经验不足（{t_exp}年/要求{req_exp}年）")
            reasons.append("工作经验部分满足")
    else:
        score += 25
        strengths.append("无经验硬性要求")

    def _skill_name(s):
        if isinstance(s, dict):
            return s.get("name") or s.get("skill") or str(s)
        return str(s)

    req_skills = {s for s in (_skill_name(x) for x in (position.skill_requirements or [])) if s}
    t_skills = {_skill_name(x).lower().strip() for x in (talent.skills_certificates or []) if _skill_name(x)}
    req_lower = {s.lower().strip() for s in req_skills}
    overlap = req_lower & t_skills
    if req_skills:
        score += 45 * (len(overlap) / len(req_skills))
        matched = [s for s in req_skills if s.lower().strip() in overlap]
        missing = [s for s in req_skills if s.lower().strip() not in overlap]
        if matched:
            strengths.append(f"技能匹配 {len(overlap)}/{len(req_skills)}（{', '.join(matched[:3])}）")
            reasons.append(f"技能匹配 {len(overlap)}/{len(req_skills)}")
        if missing:
            weaknesses.append(f"缺少技能（{', '.join(missing[:3])}）")
    else:
        score += 45
        strengths.append("无技能硬性要求")

    if t_exp > 0 and score > 0:
        score += round(min(10, t_exp * 0.3), 2)

    return {
        "score": round(min(100.0, score), 2),
        "reasons": reasons,
        "strengths": strengths,
        "weaknesses": weaknesses,
    }


