def ensure_results(db, M, tasks, papers, target=1500):
    AssessmentResult, CapabilityLevel = M["AssessmentResult"], M["CapabilityLevel"]
    Talent, TalentStatus = M["Talent"], M["TalentStatus"]
    if db.query(AssessmentResult).count() >= target:
        logger.info("[assessment_results] 已有 %d 条，跳过", db.query(AssessmentResult).count())
        return
    talents = db.query(Talent).filter(Talent.status.in_([TalentStatus.ACTIVE, TalentStatus.RESERVE])).all()
    paper_map = {p.id: p for p in papers}
    levels = list(CapabilityLevel)
    base = _next_seq(db, AssessmentResult, AssessmentResult.result_code, "AR2026") - 1
    seen = {(t, k) for t, k in db.query(AssessmentResult.talent_id, AssessmentResult.task_id).all()}
    batch, created = [], base

    for task in tasks:
        if created >= target:
            break
        paper = paper_map.get(task.paper_id) or random.choice(papers)
        sample = random.sample(talents, min(random.randint(60, 110), len(talents)))
        for t in sample:
            if created >= target:
                break
            key = (t.id, task.id)
            if key in seen:
                continue
            seen.add(key)
            # 分数与人才能力评级挂钩，保证「能力强的人分更高」
            base = (t.capability_rating or {}).get("专业技能", 70) if t.capability_rating else 70
            score = round(min(99.0, max(35.0, random.gauss(base, 8))), 2)
            qn = len(paper.questions or []) or 20
            correct = int(round(qn * score / 100))
            dims = paper.capability_dimensions or ["综合能力"]
            radar = [{"name": d, "value": round(min(99.0, max(40.0, score + random.uniform(-12, 12))), 1)} for d in dims]
            start = task.start_time + timedelta(days=random.randint(0, 10)) if task.start_time else rand_dt(90)
            submit = start + timedelta(seconds=random.randint(900, 5400))
            batch.append(AssessmentResult(
                result_code=f"AR2026{created + 1:06d}",
                talent_id=t.id, task_id=task.id, paper_id=paper.id,
                answers=[{"question_id": q.get("question_id"), "correct": random.random() < score / 100}
                         for q in (paper.questions or [])[:8]] or [{"question_id": 1, "correct": score >= 60}],
                total_score=score, correct_count=correct, wrong_count=qn - correct, unanswered_count=0,
                capability_dimensions={d["name"]: d["value"] for d in radar},
                radar_chart_data=radar,
                report=(f"本次测评总分 {score} 分（满分 100），{'达到' if score >= 60 else '未达到'}合格线 60 分。"
                        f"综合能力评级为 {('优秀' if score >= 85 else '良好' if score >= 70 else '合格' if score >= 60 else '待提升')}。"),
                strengths=f"{'、'.join(d['name'] for d in sorted(radar, key=lambda x: -x['value'])[:2])}表现突出。",
                weaknesses=f"{'、'.join(d['name'] for d in sorted(radar, key=lambda x: x['value'])[:2])}仍有提升空间。",
                suggestions="建议结合岗位要求制定针对性学习计划，并参与相关实战项目巩固提升。",
                capability_level=levels[min(len(levels) - 1, max(0, int(score // 15)))],
                start_time=start, submit_time=submit,
                duration_seconds=int((submit - start).total_seconds()),
                status="completed", created_at=submit,
            ))
            created += 1
            if len(batch) >= 500:
                db.add_all(batch)
                db.commit()
                batch.clear()
    if batch:
        db.add_all(batch)
        db.commit()
    logger.info("[assessment_results] 新增 %d 条", created - base)


