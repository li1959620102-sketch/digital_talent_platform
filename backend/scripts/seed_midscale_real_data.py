def make_id_card(gender: str, birth: date) -> str:
    """按 GB 11643-1999 生成 18 位身份证号（校验位正确，且与性别/出生日期自洽）"""
    region = random.choice(ID_REGIONS)
    seq = random.randrange(1, 1000, 2) if gender == "male" else random.randrange(2, 1000, 2)
    body = f"{region}{birth.strftime('%Y%m%d')}{seq:03d}"
    total = sum(int(body[i]) * ID_WEIGHTS[i] for i in range(17))
    return body + ID_CHECK[total % 11]


